#!/usr/bin/env python3
"""Generate the embedded Driver Station page from ui/index.html.

The page is stored gzip-compressed in flash (about a quarter of its size)
and served with Content-Encoding: gzip, so the generated header is a byte
array, not editable text. Edit ui/index.html, then run `make ui` (also run
by `make build`) and commit both files together.

Usage:
  python3 tools/gen_ui.py          write src/driverstation/esp32s3/index_html_gz.h
                                   (only if its content differs)
  python3 tools/gen_ui.py --check  fail if the header does not decompress to
                                   ui/index.html (CI drift check; compares the
                                   content, so zlib versions do not matter)
"""
import gzip
import pathlib
import re
import sys
import zlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "ui" / "index.html"
HEADER = ROOT / "src" / "driverstation" / "esp32s3" / "index_html_gz.h"

PREAMBLE = """\
#pragma once
// Generated by tools/gen_ui.py from ui/index.html. Do not edit: change the
// HTML and run `make ui`. The Driver Station page, gzip-compressed; the
// robot serves it with Content-Encoding: gzip.
#include <stddef.h>
#include <stdint.h>
#ifdef ESP32
#include <pgmspace.h>
#else
#include <avr/pgmspace.h>
#endif

"""


def render(html: bytes) -> str:
    gz = gzip.compress(html, compresslevel=9, mtime=0)
    rows = []
    for i in range(0, len(gz), 20):
        rows.append("  " + ",".join(f"0x{b:02x}" for b in gz[i:i + 20]) + ",")
    return (PREAMBLE
            + f"// {len(html)} bytes of HTML, {len(gz)} bytes compressed.\n"
            + "const uint8_t MAIN_page_gz[] PROGMEM = {\n"
            + "\n".join(rows)
            + "\n};\nconst size_t MAIN_page_gz_len = sizeof(MAIN_page_gz);\n")


def embedded(header: str) -> bytes:
    m = re.search(r"MAIN_page_gz\[\] PROGMEM = \{(.*?)\};", header, re.S)
    if not m:
        raise ValueError("no MAIN_page_gz array")
    return gzip.decompress(bytes(int(x, 16) for x in re.findall(r"0x[0-9a-f]{2}", m.group(1))))


def is_current(header: str, html: bytes) -> bool:
    """Whether the header decompresses to html; a malformed header is not."""
    try:
        return embedded(header) == html
    except (ValueError, EOFError, OSError, zlib.error):
        return False


def main() -> int:
    html = SOURCE.read_bytes()
    if sys.argv[1:] == ["--check"]:
        if not HEADER.exists() or not is_current(HEADER.read_text(), html):
            print(f"gen_ui: {HEADER.relative_to(ROOT)} is out of date; run `make ui` and commit it",
                  file=sys.stderr)
            return 1
        return 0
    if sys.argv[1:]:
        print(__doc__, file=sys.stderr)
        return 2
    # Rewrite only when the content changed: another zlib may compress the
    # same page to different bytes, which must not show up as a diff.
    if HEADER.exists() and is_current(HEADER.read_text(), html):
        return 0
    HEADER.write_text(render(html))
    return 0


if __name__ == "__main__":
    sys.exit(main())
